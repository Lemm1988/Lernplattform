<h6>Übungen mit Lösung</h6>
<p>1. Ein Arbeitsvertrag sieht 18 Urlaubstage bei einer Fünftagewoche vor. Der Betrieb ist nicht tarifgebunden. Wie viele Urlaubstage stehen der Mitarbeiterin zu?</p>
<details class="mb-3"><summary>Lösung anzeigen</summary>
<p class="mt-2">20 Tage. Das Bundesurlaubsgesetz garantiert 24 Werktage bei sechs Werktagen pro Woche; umgerechnet auf fünf Arbeitstage sind das 20 Tage. Die Vertragsklausel unterschreitet das Gesetz und ist insoweit unwirksam (Rangprinzip).</p>
</details>
<p>2. Tarifvertrag: 38 Wochenstunden. Arbeitsvertrag eines tarifgebundenen Mitarbeiters: 40 Wochenstunden ohne Lohnausgleich. Was gilt?</p>
<details class="mb-3"><summary>Lösung anzeigen</summary>
<p class="mt-2">38 Stunden. Die Abweichung im Arbeitsvertrag ist ungünstiger als der Tarifvertrag und deshalb unwirksam. Günstigere Abweichungen (z. B. 36 Stunden bei gleichem Lohn) wären erlaubt.</p>
</details>
<p>3. Eine Aufgabe lautet: „Welche zwei Aussagen sind richtig?“ Du bist dir bei drei Antworten sicher. Was tust du?</p>
<details class="mb-3"><summary>Lösung anzeigen</summary>
<p class="mt-2">Nochmals prüfen – genau zwei sind richtig. Achte auf Signalwörter und Schwellenwerte in den drei Aussagen; meist ist eine davon an einer Zahl oder an einem „immer“ falsch. Drei Kreuze bei „zwei richtigen“ werden in der Regel nicht gewertet.</p>
</details>
