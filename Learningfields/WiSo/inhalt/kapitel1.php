<h6>Strategie für gebundene Aufgaben</h6>
<ol>
  <li><strong>Frage zuerst</strong>, dann das Szenario lesen. So weißt du, welche Angabe du suchst.</li>
  <li><strong>Signalwörter</strong> markieren: „nicht“, „immer“, „ausschließlich“, „zwei Antworten“. Absolute Aussagen („immer“, „nie“) sind im Recht selten richtig.</li>
  <li><strong>Ausschlussverfahren</strong>: Erst sicher falsche Antworten streichen. Bleiben zwei, die Begründung im Gesetz suchen – Schwellenwerte (10 Beschäftigte, 6 Monate, 3 Wochen) sind beliebte Unterscheidungsmerkmale.</li>
  <li><strong>Rechenaufgaben</strong> mit Überschlag prüfen: Ein Nettolohn über dem Bruttolohn oder ein Zinssatz von 300 % ist falsch.</li>
  <li>Bei mehreren richtigen Antworten verlangt die Aufgabe genau diese Anzahl – nicht mehr ankreuzen, als gefordert sind.</li>
</ol>

<h6>Welche Regel gilt? Die Rangfolge der Rechtsquellen</h6>
<p>Ein Arbeitsverhältnis wird durch viele Regeln gleichzeitig bestimmt. Damit klar ist, welche im Zweifel gilt, stehen sie in einer festen Rangfolge:</p>
<figure class="figure w-100">
  <img src="/assets/img/lernfelder/wiso/rechtsquellen.svg" class="figure-img img-fluid w-100" style="max-width: 760px"
       alt="Pyramide von EU-Recht und Grundgesetz über Gesetze, Verordnungen, Tarifvertrag, Betriebsvereinbarung und Arbeitsvertrag bis zum Weisungsrecht; daneben Rangprinzip und Günstigkeitsprinzip mit dem Beispiel Urlaub: Gesetz 20, Tarifvertrag 30, Arbeitsvertrag 28 Tage, es gelten 30">
  <figcaption class="figure-caption">Rangprinzip und Günstigkeitsprinzip</figcaption>
</figure>
<ul>
  <li><strong>Rangprinzip</strong>: Die höhere Rechtsquelle geht vor. Ein Arbeitsvertrag kann den gesetzlichen Mindesturlaub nicht wirksam unterschreiten – die Klausel ist nichtig, es gilt das Gesetz.</li>
  <li><strong>Günstigkeitsprinzip</strong>: Eine niedrigere Ebene darf abweichen, wenn das für die Beschäftigten <em>günstiger</em> ist (§ 4 Abs. 3 Tarifvertragsgesetz). Mehr Urlaub, mehr Gehalt, kürzere Arbeitszeit sind also im Arbeitsvertrag jederzeit möglich.</li>
  <li><strong>Weisungsrecht</strong> (§ 106 Gewerbeordnung): Der Arbeitgeber legt Inhalt, Ort und Zeit der Arbeit näher fest – aber nur im Rahmen von Vertrag, Betriebsvereinbarung, Tarifvertrag und Gesetz.</li>
</ul>
<p class="lf-merke"><strong>Merke:</strong> Erst prüfen, welche Regelungen überhaupt gelten (ist der Betrieb tarifgebunden? gibt es eine Betriebsvereinbarung?), dann unter den geltenden die für die Beschäftigten günstigste wählen – solange keine höhere Regel sie verbietet.</p>

