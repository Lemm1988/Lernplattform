  <li><strong>Urabstimmung</strong>: Vor einem unbefristeten Streik stimmen die Gewerkschaftsmitglieder ab; nach den Satzungen großer Gewerkschaften ist meist eine Mehrheit von 75 % nötig. Die Quoten legt jede Gewerkschaft selbst fest.</li>
