<h6>Tarifautonomie</h6>
<p>Das Grundgesetz garantiert in Art. 9 Abs. 3 die <strong>Koalitionsfreiheit</strong>: Beschäftigte und Arbeitgeber dürfen sich zusammenschließen, um Arbeits- und Wirtschaftsbedingungen zu gestalten. Daraus folgt die <strong>Tarifautonomie</strong> – die Tarifvertragsparteien handeln Löhne und Arbeitsbedingungen ohne Einmischung des Staates aus.</p>
<ul>
  <li><strong>Tarifvertragsparteien</strong> sind auf der einen Seite Gewerkschaften, auf der anderen Arbeitgeberverbände oder einzelne Arbeitgeber.</li>
  <li><strong>Verbandstarifvertrag</strong> (Flächentarif): Gewerkschaft und Arbeitgeberverband für eine Branche und Region. <strong>Firmentarifvertrag</strong> (Haustarif): Gewerkschaft und ein einzelnes Unternehmen.</li>
</ul>

<h6>Arten von Tarifverträgen</h6>
