<h6>Rechnen mit Tariferhöhungen</h6>
<p>Eine <strong>Nominallohnerhöhung</strong> sagt, wie viel mehr Geld auf dem Konto ankommt. Ob man sich davon mehr kaufen kann, zeigt der <strong>Reallohn</strong>, der die Preissteigerung (Inflationsrate) berücksichtigt:</p>
<p class="text-center"><code>Reallohnänderung = (1 + Lohnsteigerung) / (1 + Inflationsrate) − 1</code></p>
<p>Näherungsweise genügt <code>Lohnsteigerung − Inflationsrate</code>. Beispiel: 3,5 % mehr Gehalt bei 2,2 % Inflation → (1,035 / 1,022) − 1 ≈ 1,27 %, näherungsweise 1,3 %.</p>

