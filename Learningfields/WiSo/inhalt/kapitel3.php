<h6>Für wen gilt ein Tarifvertrag?</h6>
<ul>
  <li><strong>Tarifbindung</strong>: unmittelbar und zwingend, wenn der Arbeitgeber Mitglied im Arbeitgeberverband (oder selbst Vertragspartei) <em>und</em> die beschäftigte Person Gewerkschaftsmitglied ist.</li>
